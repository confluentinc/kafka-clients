#pragma once

// The C++ shape cpp/CLAUDE.md derives from one Java type: what the header
// must declare. The clang-tidy checks compare a header with it, and
// `ck_java_model expected <FQN>` prints it for the agent writing the header.

#include <optional>
#include <string>
#include <vector>

#include "cpp_type.hpp"
#include "java_model.hpp"
#include "types.hpp"

namespace cklint::rules {

enum class TypeShape : std::uint8_t {
    CLASS,           ///< a Java class: a C++ class
    ABSTRACT_CLASS,  ///< a Java interface or abstract class (§5 "Interfaces Java declares")
    ENUM_CLASS,      ///< a Java enum (§3.3)
    ERROR_CLASS,     ///< a Throwable: generated by the error emitter (§6), members not derived here
};

enum class FunctionKind : std::uint8_t {
    CONSTRUCTOR,
    METHOD,
    STATIC_METHOD,
    FREE_FUNCTION,      ///< beside the type: an enum's members (§3.3), the §5 conventions
    CONSTANT_FUNCTION,  ///< a class-typed constant (§2.4): static, returns const&
};

struct ExpectedParameter {
    std::string name;  ///< C++ name (§2.3)
    Mapping mapping;
};

struct ExpectedFunction {
    FunctionKind kind = FunctionKind::METHOD;
    std::string name;
    std::vector<ExpectedParameter> parameters;
    Mapping returns;  ///< empty for a constructor
    bool is_virtual = false;
    bool is_pure = false;
    /// `<binary name>#<signature>` or `#<FIELD>`; empty for a C++ convention.
    std::string java_member;
    /// Why it exists when it is not a plain translation: `§5 Comparable`.
    std::string note;
};

struct ExpectedConstant {
    std::string name;
    Mapping mapping;
    std::string java_member;
    std::string initializer;
};

struct ExpectedEnumerator {
    std::string name;
    std::string value;  ///< empty when the values come from the C header's `_e` enum
};

struct ExpectedType {
    std::string java_name;
    std::string cpp_name;  ///< qualified
    std::string header;
    std::string umbrella;
    TypeShape shape = TypeShape::CLASS;
    bool functional_interface = false;
    /// The translated supertypes, qualified.
    std::vector<std::string> bases;
    /// JDK interfaces and what §5 makes of each.
    std::vector<std::string> jdk_interfaces;
    std::optional<CppType> underlying;
    std::vector<ExpectedEnumerator> enumerators;
    std::vector<ExpectedConstant> constants;
    std::vector<ExpectedFunction> functions;
    std::vector<std::string> nested;
    /// What stops generation: a shape with no §5 row, a JDK interface with no row.
    std::vector<std::string> problems;
};

ExpectedType expected(const java::Model& model, const java::Type& type);

/// A C++-like skeleton of `e`, with the Java member of each line.
std::string render(const ExpectedType& e);

}  // namespace cklint::rules
