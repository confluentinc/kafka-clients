"""Static gate: every payload view of ``kafka_common_Error_t`` that
``confluent_kafka_bindings.h`` declares (``kafka_common_Error_<class>``, returning
the class's ``kafka_common_<Class>Error_t`` or ``NULL``) is read by
``KafkaError_payload`` in ``_confluentkafka.c``, so a core error carries Java's
fields through its getters (CLAUDE.md, Python Binding Conventions, Errors), or is
listed below with the reason it is not.

The gate reads the generated header and skips when the Rust library has not
been built.
"""

import re

import pytest

from tools.ffi_twins import DEFAULT_HEADER
from tools.format_arity import DEFAULT_SOURCE

# A view of `kafka_common_Error_t`: `const kafka_common_<X>_t
# *kafka_common_Error_<name>_err(const kafka_common_Error_t *error, ...)`, other
# than the cause chain's `kafka_common_Error_source` (which returns an error).
_VIEW = re.compile(
    r"const\s+(kafka_common_\w+_t)\s*\*\s*(kafka_common_Error_\w+)_err\s*\(\s*"
    r"const\s+kafka_common_Error_t\s*\*\s*error\b")

# The views KafkaError_payload does not read, and why.
NOT_PAYLOAD = {
    # Java's CommitFailedException and RetriableCommitFailedException carry
    # their message only.
    "kafka_common_Error_consumer_commit_failed": "message only",
    "kafka_common_Error_consumer_retriable_commit_failed": "message only",
    # The Python object a callback raised, read where an error is converted
    # (`callback_exception_of`), so it comes back as the same object.
    "kafka_common_Error_local_callback_error": "the callback's own exception",
}


def payload_views(header_text):
    """The payload views a header declares, by name."""
    code = re.sub(r"/\*.*?\*/", " ", header_text, flags=re.DOTALL)
    return {name for ty, name in _VIEW.findall(code) if ty != "kafka_common_Error_t"}


def payload_body(source):
    """The body of ``py_KafkaError_payload`` in the C source."""
    start = source.index("static PyObject* py_KafkaError_payload(")
    end = source.index("\ndone:\n", start)
    return source[start:end]


def test_every_payload_view_is_read_or_listed():
    if not DEFAULT_HEADER.is_file():
        pytest.skip(f"{DEFAULT_HEADER} is generated by `cargo build --release --features ffi`, not built here")
    views = payload_views(DEFAULT_HEADER.read_text(encoding="utf-8"))
    assert "kafka_common_Error_record_deserialization" in views
    body = payload_body(DEFAULT_SOURCE.read_text(encoding="utf-8"))
    unread = sorted(v for v in views - NOT_PAYLOAD.keys() if f"{v}_err(" not in body)
    assert not unread, f"payload views KafkaError_payload does not read: {unread}"
    # The listed ones are still views, so the list does not go stale.
    assert NOT_PAYLOAD.keys() <= views


def test_the_scanner_reads_views_and_skips_the_cause_chain():
    header = """
    /** const kafka_common_FooError_t *kafka_common_Error_in_prose_err(const kafka_common_Error_t *error); */
    const kafka_common_FooError_t *kafka_common_Error_foo_err(const kafka_common_Error_t *error,
                                                              kafka_common_Error_t **out_err);
    const kafka_common_Error_t *kafka_common_Error_source_err(const kafka_common_Error_t *error,
                                                              kafka_common_Error_t **out_err);
    const char *kafka_common_FooError_bar_err(const kafka_common_FooError_t *self_,
                                              kafka_common_Error_t **out_err);
    """
    assert payload_views(header) == {"kafka_common_Error_foo"}
