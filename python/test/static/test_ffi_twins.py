"""Static gate: ``_confluentkafka.c`` calls only the C API functions that
``confluent_kafka_bindings.h`` declares, and the scanner's own tests.

The gate reads the generated header and skips when the Rust library has not
been built; the scanner's own tests need nothing built.
"""

import pytest

from tools.ffi_twins import DEFAULT_HEADER, count_names, declared_functions, load_declared, scan
from tools.format_arity import DEFAULT_SOURCE

# A slice of the bindings header: a fallible function and a `_cb` function under
# their own names, every other function only as its `_err` twin.
HEADER = """
/**
 * Mentions kafka_common_Uuid_new(1, 2) in prose, which declares nothing.
 */
kafka_common_Uuid_t *kafka_common_Uuid_new_err(int64_t a, int64_t b, kafka_common_Error_t **out_err);
kafka_common_Uuid_t *kafka_common_Uuid_from_string(const char *s, kafka_common_Error_t **out_err);
void kafka_admin_Admin_close_cb(const kafka_admin_Admin_t *self_, kafka_admin_Admin_close_cb_t cb, void *opaque);
kafka_admin_CreateTopicsOptions_t *kafka_admin_CreateTopicsOptions_new_err(kafka_common_Error_t **out_err);
void kafka_admin_FeatureUpdate_destroy_err(kafka_admin_FeatureUpdate_t *self_, kafka_common_Error_t **out_err);
typedef void (*kafka_admin_Admin_close_cb_t)(kafka_common_Error_t *error, void *opaque);
"""
DECLARED = declared_functions(HEADER)


def names(src):
    return [f.name for f in scan(src, DECLARED)]


def test_confluentkafka_c_calls_only_declared_functions():
    declared = load_declared()
    if declared is None:
        pytest.skip(f"{DEFAULT_HEADER} is generated by `cargo build --release --features ffi`, not built here")
    source = DEFAULT_SOURCE.read_text(encoding="utf-8")
    assert count_names(source) > 0, "no kafka_* names found: wrong file?"
    assert "#include <confluent_kafka_bindings.h>" in source
    findings = [f"{DEFAULT_SOURCE.name}:{f.line}: {f.name}" for f in scan(source, declared)]
    assert not findings, "\n".join(findings)


def test_the_header_declarations_are_read_without_comments_and_typedefs():
    assert DECLARED == {
        "kafka_common_Uuid_new_err",
        "kafka_common_Uuid_from_string",
        "kafka_admin_Admin_close_cb",
        "kafka_admin_CreateTopicsOptions_new_err",
        "kafka_admin_FeatureUpdate_destroy_err",
    }


def test_a_twin_call_is_clean():
    assert names("if (ffi_raise((u = kafka_common_Uuid_new_err(1, 2, &ffi_err), ffi_take(&ffi_err)))) return NULL;") == []


def test_a_fallible_and_a_cb_function_are_clean_under_their_own_names():
    assert names("u = kafka_common_Uuid_from_string(s, &ffi_err);") == []
    assert names("kafka_admin_Admin_close_cb(admin, on_closed, ctx);") == []


def test_a_plain_call_is_reported_with_its_line():
    found = scan("int a;\nkafka_common_Uuid_t* u = kafka_common_Uuid_new(1, 2);\n", DECLARED)
    assert [(f.line, f.name) for f in found] == [(2, "kafka_common_Uuid_new")]


def test_a_twin_of_a_fallible_function_is_reported():
    # A fallible function has no twin: its own name already takes out_err.
    assert names("u = kafka_common_Uuid_from_string_err(s, &ffi_err);") == ["kafka_common_Uuid_from_string_err"]


def test_a_plain_function_pointer_is_reported():
    # Compiles under a cast even with only the bindings header included.
    assert names("obj_list_init(&l, n, (handle_destroy_fn)kafka_admin_FeatureUpdate_destroy);") == [
        "kafka_admin_FeatureUpdate_destroy"]
    assert names("obj_list_init(&l, n, (handle_destroy_fn)kafka_admin_FeatureUpdate_destroy_err);") == []


def test_types_and_enumerators_are_clean():
    src = ("kafka_common_Error_t* e; kafka_common_Error_e code = kafka_common_Error_LOCAL_TIMEOUT;\n"
           "case kafka_admin_ConfigEntry_ConfigType_BOOLEAN: break;")
    assert names(src) == []


def test_a_constant_case_name_that_is_called_is_reported():
    assert names("kafka_common_Error_WAKEUP();") == ["kafka_common_Error_WAKEUP"]


def test_a_name_in_a_comment_or_a_literal_is_not_scanned():
    src = ('// kafka_common_Uuid_new(1, 2)\n/* kafka_List_size(l) */\n'
           'PyErr_SetString(PyExc_TypeError, "kafka_List_get failed");')
    assert names(src) == []


def test_a_function_the_file_defines_is_clean():
    src = ("static PyObject* kafka_principal_to_py(const void* p) { return NULL; }\n"
           "x = kafka_principal_to_py(p);")
    assert names(src) == []


def test_a_pasted_name_must_match_a_declared_function():
    assert names("var = kafka_admin_##Rpc##Options_new_err(&var##_err);") == []
    assert names("kafka_admin_##Rpc##Options_t* var = NULL;") == []
    assert names("kafka_admin_##Rpc##Options_new();") == ["kafka_admin_##…Options_new"]
    assert names("kafka_admin_##Rpc##Options_set_timeout_ms_err(o, 1, &err);") == [
        "kafka_admin_##…Options_set_timeout_ms_err"]


def test_the_c_users_header_is_reported():
    assert names("#include <confluent_kafka.h>\n") == ["confluent_kafka.h"]
    assert names("#include <confluent_kafka_bindings.h>\n") == []
