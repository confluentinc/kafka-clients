    [Fact]
    public void LiveMap_KeptKeysAndValues_SeeAMetricSetLater_AndEachEnumerationReadsTheRegistryWhenItStarts()
    {
        // Java's keySet() and values() are views of the map: a kept one sees a later registration.
        KafkaProducer<byte[], byte[]> real = KafkaProducer<byte[], byte[]>.Create(
            UnreachableProducer(), Serdes.ByteArray().Serializer(), Serdes.ByteArray().Serializer());
        using IDisposable realDisposal = TestTimeout.Disposal(real);
        MockProducer<byte[], byte[]> mock = new MockProducer<byte[], byte[]>(
            Serdes.ByteArray().Serializer(), Serdes.ByteArray().Serializer());
        using IDisposable mockDisposal = TestTimeout.Disposal(mock);
        IEnumerable<MetricName> keys = mock.Metrics().Keys;
        IEnumerable<IMetric> values = mock.Metrics().Values;
        Assert.Empty(keys);
        Assert.Empty(values);
        KafkaMetric flushTime = MockProducerMetrics.Find(real.Metrics(), FlushTime);
        MetricName first = new MetricName("first", "mock-group", "", new Dictionary<string, string>());
        MetricName second = new MetricName("second", "mock-group", "", new Dictionary<string, string>());

        MockProducerMetrics.Set(mock, first, flushTime);

        Assert.Equal(new[] { first }, keys);
        Assert.Equal(flushTime.MetricName(), Assert.Single(values).MetricName());

        using IEnumerator<MetricName> startedKeys = keys.GetEnumerator();
        using IEnumerator<IMetric> startedValues = values.GetEnumerator();
        MockProducerMetrics.Set(mock, second, flushTime);

        Assert.True(startedKeys.MoveNext());
        Assert.Equal(first, startedKeys.Current);
        Assert.False(startedKeys.MoveNext());
        Assert.True(startedValues.MoveNext());
        Assert.False(startedValues.MoveNext());
        Assert.Equal(new HashSet<MetricName> { first, second }, new HashSet<MetricName>(keys));
        Assert.Equal(2, new List<IMetric>(values).Count);
    }

