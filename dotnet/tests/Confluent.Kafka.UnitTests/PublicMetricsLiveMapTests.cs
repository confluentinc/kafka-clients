/// <summary>
/// The map a client's <c>Metrics()</c> returns, Java's <c>Collections.unmodifiableMap(metrics.metrics())</c>, without a
/// broker: a live view, so a map taken earlier sees a metric registered later; lookups, keys and values read the
/// registry; it is not an <see cref="IDictionary{TKey, TValue}"/>; and the view outlives its client and its maps, and
/// is freed by the garbage collector once nothing holds it.
/// </summary>
/// <remarks>
/// <para>
/// The metrics tests of Java's <c>KafkaConsumerTest</c> and <c>KafkaProducerTest</c>. Translated in
/// <see cref="PublicConsumerMetricsTests"/>: <c>testMetricsRemovedOnClose</c>, <c>testAssignedPartitionsMetrics</c>,
/// <c>testMetricConfigRecordingLevelInfo</c>, <c>testClosingConsumerUnregistersConsumerMetrics</c>,
/// <c>testMeasureCommitSyncDurationOnFailure</c> and <c>testMeasureCommittedDurationOnFailure</c>; in
/// <see cref="PublicProducerMetricsTests"/>: <c>testMetricConfigRecordingLevel</c>, <c>testFlushMeasureLatency</c>
/// and the producer's analogue of <c>testMetricsRemovedOnClose</c>. Not translated, with the reason:
/// </para>
/// <list type="bullet">
/// <item><description>
/// <c>KafkaConsumerTest</c>'s <c>testPollTimeMetrics</c>, <c>testPollIdleRatio</c>, <c>testPollIdleRatioZero</c>,
/// <c>testMeasureCommitSyncDuration</c> and <c>testMeasureCommittedDuration</c>, and <c>KafkaProducerTest</c>'s
/// <c>testMeasureAbortTransactionDuration</c> and <c>testMeasureTransactionDurations</c>: they assert exact values that
/// a <c>MockTime</c> the client runs on produces (the poll tests), or time calls that succeed only because a
/// <c>MockClient</c> answers the client's requests (a commit, a committed-offsets lookup, a transaction), and the
/// binding cannot inject either into the core.
/// </description></item>
/// <item><description>
/// <c>KafkaConsumerTest</c>'s <c>testSubscribingCustomMetricsDoesntAffectConsumerMetrics</c>,
/// <c>testSubscribingCustomMetricsWithSameNameDoesntAffectConsumerMetrics</c>,
/// <c>testUnsubscribingCustomMetricsWithSameNameDoesntAffectConsumerMetrics</c>,
/// <c>testUnsubscribingNonExistingMetricsDoesntCauseError</c>,
/// <c>testShouldOnlyCallMetricReporterMetricChangeOnceWithExistingConsumerMetric</c> and
/// <c>testShouldNotCallMetricReporterMetricRemovalWithExistingConsumerMetric</c>, and <c>KafkaProducerTest</c>'s
/// <c>testSubscribingCustomMetricsDoesntAffectProducerMetrics</c>,
/// <c>testUnSubscribingNonExisingMetricsDoesntCauseError</c>,
/// <c>testSubscribingCustomMetricsWithSameNameDoesntAffectProducerMetrics</c>,
/// <c>testUnsubscribingCustomMetricWithSameNameAsExistingMetricDoesntAffectProducerMetric</c>,
/// <c>testShouldOnlyCallMetricReporterMetricChangeOnceWithExistingProducerMetric</c> and
/// <c>testShouldNotCallMetricReporterMetricRemovalWithExistingProducerMetric</c>: they call
/// <c>registerMetricForSubscription</c> and <c>unregisterMetricFromSubscription</c> (KIP-714), which the C ABI does not
/// expose, so the binding does not translate them.
/// </description></item>
/// <item><description>
/// <c>KafkaConsumerTest</c>'s <c>testMetricsReporterAutoGeneratedClientId</c>,
/// <c>testConstructorInvalidMetricReporters</c>, <c>testDisableJmxAndClientTelemetryReporter</c>,
/// <c>testExplicitlyOnlyEnableJmxReporter</c>, <c>testExplicitlyOnlyEnableClientTelemetryReporter</c> and
/// <c>testConsumerJmxPrefix</c>, and <c>KafkaProducerTest</c>'s <c>testMetricsReporterAutoGeneratedClientId</c>,
/// <c>testConstructorWithInvalidMetricReporterClass</c>, <c>testDisableJmxAndClientTelemetryReporter</c>,
/// <c>testExplicitlyOnlyEnableJmxReporter</c>, <c>testExplicitlyOnlyEnableClientTelemetryReporter</c> and
/// <c>testProducerJmxPrefix</c>: they test the metric reporters (<c>metric.reporters</c>, JMX, the telemetry reporter),
/// which the binding does not translate: Java builds them from class names, which the binding's configuration does not
/// take, and .NET has no JMX.
/// </description></item>
/// </list>
/// </remarks>
