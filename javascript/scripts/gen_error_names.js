'use strict';

// Build step (binding.gyp action): writes the C switch from each
// `kafka_common_Error_e` value to its enumerator name, read from the bindings
// header, so KafkaError.name is the header's own name for the error class.
//
// Usage: node scripts/gen_error_names.js <confluent_kafka_bindings.h> <out.h>

const fs = require('node:fs');
const path = require('node:path');
const { errorEnumerators } = require('./header');

const [, , header, out] = process.argv;
if (!header || !out) {
  process.stderr.write('usage: gen_error_names.js <confluent_kafka_bindings.h> <out.h>\n');
  process.exit(2);
}
const entries = errorEnumerators(fs.readFileSync(header, 'utf8'));
const lines = [
  '// Generated by scripts/gen_error_names.js from confluent_kafka_bindings.h. Do not edit.',
  '#include "util.h"',
  '',
  'const char* error_name(int code) {',
  '    switch (code) {',
  ...entries.map(([name, value]) => `        case ${value}: return "${name}";`),
  '        default: return NULL;',
  '    }',
  '}',
  '',
];
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));
