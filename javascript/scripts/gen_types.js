'use strict';

// `make types`: generates the `.d.ts` beside every public `.js` of lib/ from
// its JSDoc with tsc (allowJs, declaration, emitDeclarationOnly; the `_`
// members the client calls across classes are `@private`, so they are
// declared private), and adds the license header. The generated
// files are committed; `--check` (test/typing) fails when one is out of date.
//
// tsc runs on a copy of lib/'s sources under build/types/, so the committed
// declarations, which tsc would resolve imports to, play no part.
//
// Usage: node scripts/gen_types.js --write | --check

const fs = require('node:fs');
const path = require('node:path');
const { ROOT, runTsc, typeRoots, writeConfig, tscCommand } = require('./typescript');

const LIB = path.join(ROOT, 'lib');
const WORK = path.join(ROOT, 'build', 'types');

/** Every file under `dir` (relative paths), recursively. */
function walk(dir, base = dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full, base));
    else out.push(path.relative(base, full));
  }
  return out.sort();
}

/** Whether a lib/ path is public: no path segment starts with `_`. */
function isPublic(rel) {
  return rel.split(path.sep).every((segment) => !segment.startsWith('_'));
}

/** The license header of a source file: its leading `//` comment block. */
function licenseOf(source) {
  const lines = fs.readFileSync(source, 'utf8').split('\n');
  const header = [];
  for (const line of lines) {
    if (!line.startsWith('//')) break;
    header.push(line);
  }
  return header.join('\n');
}

/** The declarations tsc generates for lib/, as a Map of lib-relative path to text. */
function generate() {
  fs.rmSync(WORK, { recursive: true, force: true });
  const src = path.join(WORK, 'src');
  const sources = walk(LIB).filter((rel) => rel.endsWith('.js'));
  for (const rel of sources) {
    fs.mkdirSync(path.join(src, path.dirname(rel)), { recursive: true });
    fs.copyFileSync(path.join(LIB, rel), path.join(src, rel));
  }
  const config = writeConfig(WORK, {
    compilerOptions: {
      allowJs: true,
      declaration: true,
      emitDeclarationOnly: true,
      strict: true,
      target: 'es2022',
      lib: ['es2022'],
      module: 'commonjs',
      moduleResolution: 'node10',
      types: ['node'],
      typeRoots: [typeRoots()],
      rootDir: 'src',
      declarationDir: 'out',
      newLine: 'lf',
    },
    include: ['src/**/*.js'],
  });
  const r = runTsc(['-p', config]);
  if (r.status !== 0) {
    throw new Error(`${tscCommand()} failed (exit ${r.status}):\n${r.output}`);
  }
  const out = new Map();
  for (const rel of sources.filter(isPublic)) {
    const dts = rel.replace(/\.js$/, '.d.ts');
    const text = fs.readFileSync(path.join(WORK, 'out', dts), 'utf8');
    const banner = `// Generated by \`make types\` from the JSDoc of ${path.basename(rel)}; do not edit.`;
    out.set(dts, `${licenseOf(path.join(LIB, rel))}\n\n${banner}\n\n${text}`);
  }
  return out;
}

/** The `.d.ts` files lib/ has now. */
function committed() {
  return walk(LIB).filter((rel) => rel.endsWith('.d.ts'));
}

function main(mode) {
  const generated = generate();
  if (mode === '--write') {
    for (const rel of committed()) if (!generated.has(rel)) fs.rmSync(path.join(LIB, rel));
    for (const [rel, text] of generated) fs.writeFileSync(path.join(LIB, rel), text);
    return 0;
  }
  const problems = [];
  for (const [rel, text] of generated) {
    const file = path.join(LIB, rel);
    if (!fs.existsSync(file)) problems.push(`lib/${rel} is missing`);
    else if (fs.readFileSync(file, 'utf8') !== text) problems.push(`lib/${rel} is out of date`);
  }
  for (const rel of committed()) if (!generated.has(rel)) problems.push(`lib/${rel} has no public source`);
  if (problems.length > 0) {
    process.stderr.write(`${problems.join('\n')}\nrun \`make -C javascript types\` and commit the result\n`);
    return 1;
  }
  return 0;
}

const mode = process.argv[2];
if (mode !== '--write' && mode !== '--check') {
  process.stderr.write('usage: gen_types.js --write | --check\n');
  process.exit(2);
}
process.exitCode = main(mode);
