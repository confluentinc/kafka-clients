'use strict';

// Reads confluent_kafka_bindings.h for the build (scripts/gen_error_names.js)
// and the header-conformance unit test. Plain text scanning: the header is
// generated by cbindgen in one fixed style, a declaration starting at column 0.

const fs = require('node:fs');
const path = require('node:path');

/** The bindings header the addon is built against. */
function headerPath() {
  const dir = path.resolve(
    process.env.CONFLUENT_KAFKA_INCLUDE_DIR || path.join(__dirname, '..', '..', 'rust', 'target', 'include'),
  );
  return path.join(dir, 'confluent_kafka_bindings.h');
}

/** Strips C block and line comments. */
function stripComments(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

/** The names of every function the header declares. */
function declaredFunctions(text) {
  const names = new Set();
  const code = stripComments(text);
  // A declaration: a return type at column 0, then the name and `(`.
  const re = /^[A-Za-z_][\w \t*]*?\b(kafka_\w+)\s*\(/gm;
  let m;
  while ((m = re.exec(code)) !== null) names.add(m[1]);
  return names;
}

/** The `[name, value]` enumerators of `kafka_common_Error_e`, name without its prefix. */
function errorEnumerators(text) {
  const code = stripComments(text);
  const end = code.indexOf('} kafka_common_Error_e;');
  if (end < 0) throw new Error('kafka_common_Error_e not found in the bindings header');
  const start = code.lastIndexOf('typedef enum {', end);
  const body = code.slice(start + 'typedef enum {'.length, end);
  const out = [];
  const re = /kafka_common_Error_([A-Z0-9_]+)\s*=\s*(-?\d+)/g;
  let m;
  while ((m = re.exec(body)) !== null) out.push([m[1], Number(m[2])]);
  if (out.length === 0) throw new Error('kafka_common_Error_e has no enumerators');
  return out;
}

module.exports = { headerPath, stripComments, declaredFunctions, errorEnumerators };
