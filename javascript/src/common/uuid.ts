// Java's org.apache.kafka.common.Uuid, translated from the Java source: two
// Java longs as bigints, base64 (URL alphabet, no padding) in toString() and
// fromString(), Java's equals, hashCode and compareTo. Its getters start
// with `get`, so they stay methods (javascript/CLAUDE.md, JavaScript Binding
// Conventions, Class family).

import { randomBytes } from 'node:crypto';

import { JavaForms, kind } from '../internal/args';
import { checkLong } from '../internal/java_number';
import { readOnlySet } from '../internal/read_only_set';
import { IllegalArgumentError } from '../illegal_argument_error';

const CONSTRUCTOR_FORMS = new JavaForms('Uuid', [['mostSigBits', 'leastSigBits']]);
const FROM_STRING_FORMS = new JavaForms('fromString', [['str']], { bareTypes: { str: (v) => v === null || typeof v === 'string' } });
const isIterable = (v: unknown): boolean =>
  v !== null && typeof v === 'object' && typeof (v as { [Symbol.iterator]?: unknown })[Symbol.iterator] === 'function';
// Java's List<Uuid>: any iterable (javascript/CLAUDE.md, JavaScript Binding Conventions, Class family).
const TO_ARRAY_FORMS = new JavaForms('toArray', [['list']], { bareTypes: { list: (v) => v === null || isIterable(v) } });
const TO_LIST_FORMS = new JavaForms('toList', [['array']], { bareTypes: { array: (v) => v === null || Array.isArray(v) } });
const EQUALS_FORMS = new JavaForms('equals', [['obj']]);
const COMPARE_TO_FORMS = new JavaForms('compareTo', [['other']], { bareTypes: { other: (v) => v === null || v instanceof Uuid } });
const READER = (name: string): JavaForms => new JavaForms(name, [[]], { reader: true });
const RANDOM_UUID_FORMS = READER('randomUuid');
const MOST_FORMS = READER('getMostSignificantBits');
const LEAST_FORMS = READER('getLeastSignificantBits');
const HASH_CODE_FORMS = READER('hashCode');

const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';

/**
 * Java's `Base64.getUrlDecoder().decode(str)`: the URL alphabet, padding
 * optional, with Java's messages for a character outside it and for a last
 * unit too short.
 *
 * @param str - the text
 * @returns the bytes
 */
function decodeBase64Url(str: string): Buffer {
  let end = str.length;
  // Java's decoder takes `=` padding only at the end.
  while (end > 0 && str[end - 1] === '=') end -= 1;
  for (let i = 0; i < end; i++) {
    if (!ALPHABET.includes(str[i])) {
      throw new IllegalArgumentError(`Illegal base64 character ${str.charCodeAt(i).toString(16)}`);
    }
  }
  if (end % 4 === 1) throw new IllegalArgumentError('Last unit does not have enough valid bits');
  // Each character is 6 bits, read into whole bytes (the text is ASCII, so
  // no string is encoded).
  const out = Buffer.alloc(Math.floor((end * 6) / 8));
  let bits = 0;
  let acc = 0;
  let n = 0;
  for (let i = 0; i < end; i++) {
    acc = (acc << 6) | ALPHABET.indexOf(str[i]);
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      out[n++] = (acc >> bits) & 0xff;
    }
  }
  return out;
}

/**
 * This class defines an immutable universally unique identifier (UUID). It
 * represents a 128-bit value. More specifically, the random UUIDs generated
 * by this class are variant 2 (Leach-Salz) version 4 UUIDs. This is the same
 * type of UUID as the ones generated by java.util.UUID. The toString() method
 * prints using the base64 string encoding. Likewise, the fromString method
 * expects a base64 string encoding.
 *
 * @remarks Java's two `long` halves are bigints.
 */
export class Uuid {
  readonly #mostSignificantBits: bigint;
  readonly #leastSignificantBits: bigint;

  /**
   * Constructs a 128-bit type 4 UUID where the first long represents the
   * most significant 64 bits and the second long represents the least
   * significant 64 bits.
   *
   * @param options - the most significant and the least significant bits
   * @throws `IllegalArgumentError` when the given parameters are not
   *   `{mostSigBits, leastSigBits}`
   * @throws `TypeError` or `RangeError` when a half is not a Java `long`
   */
  constructor(options: {
    /** The most significant 64 bits. */
    mostSigBits: bigint | number;
    /** The least significant 64 bits. */
    leastSigBits: bigint | number;
  }) {
    CONSTRUCTOR_FORMS.match(options, arguments.length);
    this.#mostSignificantBits = checkLong(CONSTRUCTOR_FORMS.value(options, 'mostSigBits'), 'mostSigBits');
    this.#leastSignificantBits = checkLong(CONSTRUCTOR_FORMS.value(options, 'leastSigBits'), 'leastSigBits');
    Object.freeze(this);
  }

  /** A reserved UUID. Will never be returned by the randomUuid method. */
  static readonly ONE_UUID: Uuid = new Uuid({ mostSigBits: 0n, leastSigBits: 1n });

  /** A UUID for the metadata topic in KRaft mode. Will never be returned by the randomUuid method. */
  static readonly METADATA_TOPIC_ID: Uuid = Uuid.ONE_UUID;

  /** A UUID that represents a null or empty UUID. Will never be returned by the randomUuid method. */
  static readonly ZERO_UUID: Uuid = new Uuid({ mostSigBits: 0n, leastSigBits: 0n });

  /** The set of reserved UUIDs that will never be returned by the randomUuid method. */
  static readonly RESERVED: ReadonlySet<Uuid> = readOnlySet([Uuid.ZERO_UUID, Uuid.ONE_UUID]);

  /**
   * Static factory to retrieve a type 4 (pseudo randomly generated) UUID.
   *
   * This will not generate a UUID equal to 0, 1, or one whose string
   * representation contains a dash ("-").
   *
   * @returns a random UUID
   * @throws `TypeError` when it is given an argument: it only reads
   */
  static randomUuid(): Uuid {
    if (arguments.length !== 0) RANDOM_UUID_FORMS.match(undefined, arguments.length);
    for (;;) {
      // java.util.UUID.randomUUID(): version 4, variant 2.
      const bytes = randomBytes(16);
      bytes[6] = (bytes[6] & 0x0f) | 0x40;
      bytes[8] = (bytes[8] & 0x3f) | 0x80;
      const uuid = new Uuid({ mostSigBits: bytes.readBigInt64BE(0), leastSigBits: bytes.readBigInt64BE(8) });
      if (uuid.equals(Uuid.ZERO_UUID) || uuid.equals(Uuid.ONE_UUID) || uuid.toString().includes('-')) continue;
      return uuid;
    }
  }

  /**
   * Returns the most significant bits of the UUID's 128 value.
   *
   * @returns the most significant 64 bits
   * @throws `TypeError` when it is given an argument: it only reads
   */
  getMostSignificantBits(): bigint {
    if (arguments.length !== 0) MOST_FORMS.match(undefined, arguments.length);
    return this.#mostSignificantBits;
  }

  /**
   * Returns the least significant bits of the UUID's 128 value.
   *
   * @returns the least significant 64 bits
   * @throws `TypeError` when it is given an argument: it only reads
   */
  getLeastSignificantBits(): bigint {
    if (arguments.length !== 0) LEAST_FORMS.match(undefined, arguments.length);
    return this.#leastSignificantBits;
  }

  /**
   * Returns true iff obj is another Uuid represented by the same two long values.
   *
   * @param obj - the value to compare with, on its own or as `{ obj }`
   * @returns whether it is an equal Uuid
   */
  equals(obj: unknown): boolean {
    EQUALS_FORMS.match(obj, arguments.length);
    const other = EQUALS_FORMS.value(obj, 'obj');
    if (other === null || other === undefined || Object.getPrototypeOf(other) !== Object.getPrototypeOf(this)) return false;
    const id = other as Uuid;
    return this.#mostSignificantBits === id.#mostSignificantBits && this.#leastSignificantBits === id.#leastSignificantBits;
  }

  /**
   * Returns a hash code for this UUID.
   *
   * @returns Java's `(int) (xor >> 32) ^ (int) xor` of the two halves
   * @throws `TypeError` when it is given an argument: it only reads
   */
  hashCode(): number {
    if (arguments.length !== 0) HASH_CODE_FORMS.match(undefined, arguments.length);
    const xor = BigInt.asIntN(64, this.#mostSignificantBits ^ this.#leastSignificantBits);
    return Number(BigInt.asIntN(32, xor >> 32n)) ^ Number(BigInt.asIntN(32, xor));
  }

  /**
   * Returns a base64 string encoding of the UUID.
   *
   * @returns the base64 URL encoding of the 16 bytes, without padding
   */
  toString(): string {
    const bytes = Buffer.alloc(16);
    bytes.writeBigInt64BE(this.#mostSignificantBits, 0);
    bytes.writeBigInt64BE(this.#leastSignificantBits, 8);
    return bytes.toString('base64url');
  }

  /**
   * The UUID as `JSON.stringify` writes it: its `toString()` text.
   *
   * @returns the base64 string encoding
   *
   * @remarks *(js-only)* JavaScript's JSON protocol, whose output is frozen
   * once released.
   */
  toJSON(): string {
    return this.toString();
  }

  /**
   * Creates a UUID based on a base64 string encoding used in the toString() method.
   *
   * @param str - the base64 encoding, on its own or as `{ str }`
   * @returns the UUID
   * @throws `IllegalArgumentError` when the text is longer than 24
   *   characters, is not base64, or does not decode to 16 bytes
   * @throws `TypeError` when it is null or not a string
   */
  static fromString(str: string): Uuid;
  /**
   * The same as `fromString(str)`, the parameter given by name.
   *
   * @param options - the base64 encoding
   * @returns the UUID
   * @throws `IllegalArgumentError` when the text is longer than 24
   *   characters, is not base64, or does not decode to 16 bytes
   * @throws `TypeError` when it is null or not a string
   */
  static fromString(options: {
    /** The base64 encoding */
    str: string;
  }): Uuid;
  static fromString(str: unknown): Uuid {
    FROM_STRING_FORMS.match(str, arguments.length);
    const text = FROM_STRING_FORMS.value(str, 'str');
    // Java dereferences the string (`str.length()`).
    if (text === null) throw new TypeError('str must not be null');
    if (typeof text !== 'string') throw new TypeError('str must be a string');
    if (text.length > 24) {
      throw new IllegalArgumentError(`Input string with prefix \`${text.substring(0, 24)}\` is too long to be decoded as a base64 UUID`);
    }
    const bytes = decodeBase64Url(text);
    if (bytes.length !== 16) {
      throw new IllegalArgumentError(
        `Input string \`${text}\` decoded as ${bytes.length} bytes, which is not equal to the expected 16 bytes of a base64-encoded UUID`,
      );
    }
    return new Uuid({ mostSigBits: bytes.readBigInt64BE(0), leastSigBits: bytes.readBigInt64BE(8) });
  }

  /**
   * Compares this UUID with another by their most, then least, significant
   * bits, as signed longs.
   *
   * @param other - the UUID to compare with, on its own or as `{ other }`
   * @returns -1, 0 or 1
   * @throws `TypeError` when it is null (Java dereferences it)
   */
  compareTo(other: Uuid): number;
  /**
   * The same as `compareTo(other)`, the parameter given by name.
   *
   * @param options - the UUID to compare with
   * @returns -1, 0 or 1
   * @throws `TypeError` when it is null (Java dereferences it)
   */
  compareTo(options: {
    /** The UUID to compare with */
    other: Uuid;
  }): number;
  compareTo(other: unknown): number {
    COMPARE_TO_FORMS.match(other, arguments.length);
    const o = COMPARE_TO_FORMS.value(other, 'other');
    if (!(o instanceof Uuid)) throw new TypeError(o === null ? 'other must not be null' : 'other must be a Uuid');
    if (this.#mostSignificantBits !== o.#mostSignificantBits) return this.#mostSignificantBits > o.#mostSignificantBits ? 1 : -1;
    if (this.#leastSignificantBits !== o.#leastSignificantBits) return this.#leastSignificantBits > o.#leastSignificantBits ? 1 : -1;
    return 0;
  }

  /**
   * Convert a list of Uuid to an array of Uuid.
   *
   * @param list - The input list (any iterable), or `{ list }`
   * @returns The output array (null for a null list)
   */
  static toArray(list: Iterable<Uuid> | null): Uuid[] | null;
  /**
   * The same as `toArray(list)`, the parameter given by name.
   *
   * @param options - The input list
   * @returns The output array (null for a null list)
   */
  static toArray(options: {
    /** The input list, any iterable */
    list: Iterable<Uuid> | null;
  }): Uuid[] | null;
  static toArray(list: unknown): Uuid[] | null {
    TO_ARRAY_FORMS.match(list, arguments.length);
    const value = TO_ARRAY_FORMS.value(list, 'list');
    if (value === null) return null;
    if (!isIterable(value)) throw new TypeError(`list must be an iterable of Uuid, not ${kind(value)}`);
    return [...(value as Iterable<Uuid>)];
  }

  /**
   * Convert an array of Uuids to a list of Uuid.
   *
   * @param array - The input array, or `{ array }`
   * @returns The output list (null for a null array)
   */
  static toList(array: ReadonlyArray<Uuid> | null): Uuid[] | null;
  /**
   * The same as `toList(array)`, the parameter given by name.
   *
   * @param options - The input array
   * @returns The output list (null for a null array)
   */
  static toList(options: {
    /** The input array */
    array: ReadonlyArray<Uuid> | null;
  }): Uuid[] | null;
  static toList(array: unknown): Uuid[] | null {
    TO_LIST_FORMS.match(array, arguments.length);
    const value = TO_LIST_FORMS.value(array, 'array') as ReadonlyArray<Uuid> | null;
    return value === null ? null : [...value];
  }

  /**
   * The key of a `UuidMap`: the fields `equals` compares, the two halves, as
   * the base64 text `toString()` writes. Called by `UuidMap`.
   *
   * @returns the key
   *
   * @internal
   */
  internalKey(): string {
    return this.toString();
  }
}
